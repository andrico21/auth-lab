import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {DNSSEC_MATERIAL} from '../../src/dnssec-fixtures.js';

// Application data projection only, not an independent signature-verification oracle.
// Hash the exact public RRSIG RDATA with the host's crypto library; standalone uses static data.
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const mode=process.argv[2];
assert.ok(['--write','--check'].includes(mode)&&process.argv.length===3,'Use --write or --check');
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const signatures=Object.keys(DNSSEC_MATERIAL.signatures).sort();
const values=Object.fromEntries(signatures.map(id=>{
  const signature=DNSSEC_MATERIAL.signatures[id],hex=signature.rrsigRdataHex;
  assert.ok(typeof hex==='string'&&hex.length>0&&hex.length%2===0&&/^[0-9a-f]+$/i.test(hex),'Exact public RRSIG RDATA required: '+id);
  return [id,hash(Buffer.from(hex,'hex'))];
}));
const output='src/dnssec-signature-fingerprints.js';
const text='// Generated by tools/verification/build-dnssec-signature-fingerprints.mjs.\n// SHA256 of exact public RRSIG RDATA; no private material or runtime cryptography.\nexport const DNSSEC_SIGNATURE_RDATA_SHA256=Object.freeze('+JSON.stringify(values,null,2)+');\n';
if(mode==='--write')fs.writeFileSync(path.join(root,output),text);
else assert.equal(fs.readFileSync(path.join(root,output),'utf8'),text,'Public RRSIG fingerprint projection must match actual Source RDATA');
console.log(JSON.stringify({result:mode==='--write'?'written':'checked',scope:'Public application data projection, not signature verification',signatures:signatures.length,output,bytes:Buffer.byteLength(text),sha256:hash(text)}));
