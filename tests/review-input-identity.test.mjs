import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {captureReviewInputs} from '../tools/verification/review-input-identity.mjs';

function withInputs(run){
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'review-input-boundary-'));
  try{
    for(const directory of ['assets','src','tests','tools/verification/dnssec-crypto','docs/next-expansion','dist'])fs.mkdirSync(path.join(root,directory),{recursive:true});
    for(const [name,value] of Object.entries({'index.html':'<main>fixture</main>','build.mjs':'export {};','package.json':'{}','security-policy.mjs':'export {};','docs/next-expansion/scenario-manifest.json':'{}','dist/auth-flow-studio.html':'<main>built</main>','tools/verification/runner.mjs':'export {};','tools/verification/dnssec-crypto/generate.py':'print("reference")\n','tools/verification/dnssec-crypto/requirements.txt':'dns-tool==1\n'}))fs.writeFileSync(path.join(root,name),value);
    run(root,path.join(root,'tools/verification/runner.mjs'));
  }finally{fs.rmSync(root,{recursive:true,force:true});}
}

test('generated verification environments cannot invalidate pinned source evidence, but generator changes must',()=>withInputs((root,runner)=>{
  const crypto=path.join(root,'tools/verification/dnssec-crypto');
  for(const name of ['.venv','.offline-venv']){
    fs.mkdirSync(path.join(crypto,name,'bin'),{recursive:true});
    fs.symlinkSync(process.execPath,path.join(crypto,name,'bin/python'));
    fs.writeFileSync(path.join(crypto,name,'pyvenv.cfg'),'generated environment\n');
  }
  fs.mkdirSync(path.join(crypto,'__pycache__'));
  fs.writeFileSync(path.join(crypto,'__pycache__/generate.pyc'),'first bytecode cache');
  const before=captureReviewInputs(root,runner);
  fs.writeFileSync(path.join(crypto,'.venv/pyvenv.cfg'),'different local interpreter path\n');
  fs.writeFileSync(path.join(crypto,'__pycache__/generate.pyc'),'regenerated bytecode cache');
  assert.deepEqual(captureReviewInputs(root,runner),before);
  fs.writeFileSync(path.join(crypto,'generate.py'),'print("changed reference algorithm")\n');
  const after=captureReviewInputs(root,runner);
  assert.notEqual(after.verificationFiles['tools/verification/dnssec-crypto/generate.py'],before.verificationFiles['tools/verification/dnssec-crypto/generate.py']);
  assert.deepEqual(after.sourceFiles,before.sourceFiles);
}));

test('a generated-environment directory name cannot hide a runtime source symlink',()=>withInputs((root,runner)=>{
  fs.mkdirSync(path.join(root,'src/.venv'));
  fs.symlinkSync(process.execPath,path.join(root,'src/.venv/stealth.mjs'));
  assert.throws(()=>captureReviewInputs(root,runner),/Review input symlink: src\/\.venv\/stealth\.mjs/);
}));
